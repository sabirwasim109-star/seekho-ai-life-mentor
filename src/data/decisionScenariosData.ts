export function getScenarioByCategory(category: string): DecisionScenario | undefined {
  return DECISION_SCENARIOS_DATA.find(s => s.category === category);
}

export function searchScenarios(query: string, language: Language = 'ur'): DecisionScenario[] {
  const q = query.toLowerCase().trim();
  if (!q) return DECISION_SCENARIOS_DATA;

  return DECISION_SCENARIOS_DATA.filter(s => {
    return (
      s.titleUrdu.toLowerCase().includes(q) ||
      s.titleEn.toLowerCase().includes(q) ||
      s.situationUrdu.toLowerCase().includes(q) ||
      s.situationEn.toLowerCase().includes(q) ||
      s.category.toLowerCase().includes(q)
    );
  });
}
