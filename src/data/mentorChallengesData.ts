/**
 * Returns customized challenges grouped or matched to user context.
 */
export function getRecommendedChallengesForUser(userProfile?: UserProfile, language: Language = 'ur'): MentorChallenge[] {
  // Return top 1 challenge of each of the 5 types
  const types: MentorChallengeType[] = ['daily', 'seven_day', 'character', 'skill', 'community'];
  const result: MentorChallenge[] = [];

  const completedIds = userProfile?.completedGrowthTaskIds || [];

  for (const t of types) {
    const list = MENTOR_CHALLENGES.filter((c) => c.type === t);
    // Find first not yet completed or default to first
    const uncompleted = list.find((c) => !completedIds.includes(c.id));
    result.push(uncompleted || list[0]);
  }

  return result;
}
